# Anything in this set is never passed to domain RapidFuzz.
FUZZY_SKIP: frozenset[str] = INTENT_OPERATORS | FILLER_TOKENS | COMMON_ENGLISH_SKIP

# Back-compat alias used by unresolved filtering of intent-bearing words.
INTENT_VOCABULARY = INTENT_OPERATORS


def is_fuzzy_skip_token(token: str) -> bool:
    return token.lower() in FUZZY_SKIP


def is_intent_operator(token: str) -> bool:
    return token.lower() in INTENT_OPERATORS
